#!/usr/bin/env node
/**
 * Writes docs/VERIFICATION_CHECKLIST.md: every community value that was
 * transcribed from search excerpts of official pages, with the page to check
 * it against, plus the gaps that should only be filled from official pages.
 *
 * Reads the existing data and never changes it. Any "Confirmed on / by"
 * entries already in the checklist are kept when it is regenerated.
 *
 * Usage: npm run build:checklist
 */
import { readFile, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createServer } from 'vite';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outFile = path.join(root, 'docs', 'VERIFICATION_CHECKLIST.md');

/** Sources whose values came from search excerpts of official pages. */
const EXCERPT_SOURCES = {
  population: ['statcan-2021-fogs'],
  location: ['nrcan-cgndb', 'gov-nunavut-communities'],
};

// Load the TypeScript modules through Vite (already a dependency), so the
// register and URL helper are the same code the app uses.
const vite = await createServer({ root, logLevel: 'error', server: { middlewareMode: true }, appType: 'custom' });
let DATA_SOURCES;
let statCanProfileUrl;
try {
  ({ DATA_SOURCES } = await vite.ssrLoadModule('/src/data/sources/sources.ts'));
  ({ statCanProfileUrl } = await vite.ssrLoadModule('/src/lib/links.ts'));
} finally {
  await vite.close();
}

const { communities } = JSON.parse(await readFile(path.join(root, 'src/data/communities/communities.json'), 'utf8'));
communities.sort((a, b) => a.name.localeCompare(b.name, 'en-CA'));
const sourceUrl = (id) => DATA_SOURCES.find((s) => s.id === id)?.url ?? '';
const sourceName = (id) => DATA_SOURCES.find((s) => s.id === id)?.name ?? id;

/** Keep confirmations people have already written into the checklist. */
async function existingConfirmations() {
  const kept = new Map();
  if (!existsSync(outFile)) return kept;
  for (const line of (await readFile(outFile, 'utf8')).split('\n')) {
    const cells = line.split('|').map((c) => c.trim());
    // | Community | Field | Value | Source | Check against | Confirmed |
    if (cells.length === 8 && cells[6] && !/^-+$/.test(cells[6]) && cells[6] !== 'Confirmed on / by') {
      kept.set(`${cells[1]}|${cells[2]}`, cells[6]);
    }
  }
  return kept;
}
const confirmed = await existingConfirmations();

const fmtCoord = (loc) => `${loc.lat.toFixed(6)}, ${loc.lon.toFixed(6)}`;
const link = (url) => (url ? `<${url}>` : '');
const linkFor = (c, sourceId) => c.links?.find((l) => l.sourceId === sourceId)?.url;

const rows = [];
for (const c of communities) {
  const pop = c.population;
  if (pop) {
    for (const sourceId of pop.sourceIds.filter((id) => EXCERPT_SOURCES.population.includes(id))) {
      const url = c.censusSubdivisionCode ? statCanProfileUrl(c.censusSubdivisionCode) : sourceUrl(sourceId);
      rows.push([c.name, `Population (${pop.censusYear} Census)`, pop.count.toLocaleString('en-CA'), sourceId, url]);
    }
  }
  const loc = c.location;
  if (loc) {
    for (const sourceId of loc.sourceIds.filter((id) => EXCERPT_SOURCES.location.includes(id))) {
      const url = linkFor(c, sourceId) ?? sourceUrl(sourceId);
      rows.push([c.name, `Coordinates (${sourceId === 'nrcan-cgndb' ? 'CGNDB' : 'Government of Nunavut'})`, fmtCoord(loc), sourceId, url]);
    }
  }
}

const escape = (text) => String(text).replace(/\|/g, '\\|');
const tableLines = [
  '| Community | Field | Current value | Source id | Check against | Confirmed on / by |',
  '| --- | --- | --- | --- | --- | --- |',
  ...rows.map(([name, field, value, sourceId, url]) => {
    const done = confirmed.get(`${name}|${field}`) ?? '';
    return `| ${escape(name)} | ${escape(field)} | ${escape(value)} | \`${sourceId}\` | ${link(url)} | ${escape(done)} |`;
  }),
];

const missingPopulation = communities.filter((c) => !c.population);
const missingCsd = communities.filter((c) => !c.censusSubdivisionCode);
const singleSource = communities.filter((c) => c.location?.verification === 'single-source');

const content = `# Data verification checklist

Generated by \`npm run build:checklist\` (scripts/build-verification-checklist.mjs) from the current data. Do not edit the
values here; they mirror \`src/data/communities/communities.json\`.

When this release was built, Statistics Canada, NRCan and Government of Nunavut pages could not be opened directly. These
values were transcribed from search-engine excerpts of the official pages (see [DATA_SOURCES.md](DATA_SOURCES.md)). Open each
page, compare the value, and write the date and your name in the last column. Regenerating keeps what you wrote there.

If a value is wrong, correct it in \`communities.json\` in a separate pull request that cites the page, then regenerate
this file.

## Values to confirm (${rows.length})

${tableLines.join('\n')}

## Gaps to fill only from official pages

Add these only from the official source named, never from secondary sites.

### Missing 2021 Census populations (${missingPopulation.length})

Source: ${sourceName('statcan-2021-fogs')}, ${link(sourceUrl('statcan-2021-fogs'))}

${missingPopulation.map((c) => `- [ ] ${c.name}`).join('\n')}

### Missing census subdivision codes (${missingCsd.length})

Source: ${sourceName('statcan-2021-fogs')}, ${link(sourceUrl('statcan-2021-fogs'))}. The code is the last seven digits of the
community's DGUID (\`2021A0005\` + code).

${missingCsd.map((c) => `- [ ] ${c.name}`).join('\n')}

### Single-source coordinates to check against CGNDB (${singleSource.length})

Source: ${sourceName('nrcan-cgndb')}, ${link(sourceUrl('nrcan-cgndb'))}

${singleSource.map((c) => `- [ ] ${c.name}: currently ${fmtCoord(c.location)} (${c.location.sourceIds.join(', ')})`).join('\n')}
`;

await writeFile(outFile, content);
console.log(`Wrote ${path.relative(root, outFile)}: ${rows.length} values to confirm, ${missingPopulation.length + missingCsd.length + singleSource.length} gaps.`);
